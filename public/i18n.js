export const LANGUAGE_OPTIONS = [
  ['en', 'English'],
  ['zh-CN', '简体中文'],
  ['zh-TW', '繁體中文'],
  ['fr', 'Français'],
  ['es', 'Español'],
  ['ja', '日本語'],
  ['ar', 'العربية'],
  ['de', 'Deutsch'],
  ['it', 'Italiano'],
  ['pt', 'Português']
];

let currentLanguage = 'en';

function normalizeLanguage(value) {
  const language = String(value || '').replace('_', '-');
  if (translations[language]) return language;
  const lower = language.toLowerCase();
  if (lower.startsWith('zh-tw') || lower.startsWith('zh-hk') || lower.startsWith('zh-hant')) return 'zh-TW';
  if (lower.startsWith('zh')) return 'zh-CN';
  return LANGUAGE_OPTIONS.find(([code]) => lower.startsWith(code.toLowerCase()))?.[0] || 'en';
}

function interpolate(template, variables = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => (
    variables[key] === undefined ? `{${key}}` : String(variables[key])
  ));
}

export function t(key, variables) {
  const message = translations[currentLanguage]?.[key] ?? translations.en[key] ?? key;
  return interpolate(message, variables);
}

export function getLanguage() {
  return currentLanguage;
}

export function getLocale() {
  return currentLanguage;
}

export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-title]').forEach(element => {
    element.title = t(element.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach(element => {
    element.setAttribute('aria-label', t(element.dataset.i18nAria));
  });
  document.documentElement.lang = currentLanguage;
  document.documentElement.dir = currentLanguage === 'ar' ? 'rtl' : 'ltr';
  document.title = 'ChatGPT Vault';
}

export function setLanguage(value, { persist = true, notify = true } = {}) {
  currentLanguage = normalizeLanguage(value);
  if (persist && typeof localStorage !== 'undefined') {
    localStorage.setItem('chatgpt-vault-language', currentLanguage);
  }
  if (typeof document !== 'undefined') applyTranslations(document);
  if (notify && typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('chatgpt-vault-languagechange', {
      detail: { language: currentLanguage }
    }));
  }
  return currentLanguage;
}

export function initI18n() {
  const saved = typeof localStorage !== 'undefined'
    ? localStorage.getItem('chatgpt-vault-language')
    : '';
  const browserLanguage = typeof navigator !== 'undefined'
    ? navigator.languages?.[0] || navigator.language
    : 'en';
  return setLanguage(saved || browserLanguage, { persist: Boolean(saved), notify: false });
}
